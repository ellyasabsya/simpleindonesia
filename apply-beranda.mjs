// 2) poster-card.tsx: tujuh penggantian, masing-masing harus cocok tepat satu kali
let card = fs.readFileSync(CARD, 'utf8');
if (card.includes('\r\n')) fail('poster-card.tsx memakai CRLF, kirim berkasnya ke saya');
const before = card;
const R = [
  ["    berlangsung: 'bg-emerald-500',\n    segera: 'bg-blue-600',\n    selesai: 'bg-neutral-600',",
   "    berlangsung: 'bg-emerald-400',\n    segera: 'bg-sky-400',\n    selesai: 'bg-neutral-400',"],
  ["'absolute top-3 left-3 inline-flex items-center gap-1.5 rounded-full px-3 py-1 text-[11px] font-semibold text-white shadow-lg ' + STATUS[event.status.key]",
   "'absolute top-3 left-3 inline-flex items-center gap-1.5 rounded-full bg-black/35 px-3 py-1 text-[11px] font-medium text-white ring-1 ring-white/20 backdrop-blur-md'"],
  ['<span className="size-1.5 rounded-full bg-white" />',
   "<span className={'size-1.5 rounded-full ' + STATUS[event.status.key]} />"],
  ['bg-gradient-to-br from-indigo-600 via-violet-600 to-fuchsia-600">',
   'bg-[radial-gradient(120%_90%_at_20%_0%,#4f46e5_0%,#1e1b4b_55%,#0b0a1f_100%)]">'],
  ['text-6xl font-black tracking-wide text-white/90',
   'text-7xl font-semibold tracking-tight text-white/25'],
  ["'line-clamp-2 leading-tight font-extrabold text-white ' + (compact ? 'text-[14px]' : 'text-[19px]')",
   "'line-clamp-2 leading-tight font-semibold tracking-tight text-white ' + (compact ? 'text-[14px]' : 'text-[22px]')"],
  ['mb-1 text-[11px] font-semibold tracking-[0.14em] text-white/70 uppercase',
   'mb-1.5 text-[10px] font-medium tracking-[0.2em] text-white/70 uppercase'],
];
let cardDone = 0;
for (const [o, n] of R) {
  const c = card.split(o).length - 1;
  if (c === 1) card = card.replace(o, () => n);
  else if (c === 0 && card.includes(n)) cardDone++;
  else fail('poster-card.tsx: pola tidak cocok (' + c + 'x): ' + o.slice(0, 60));
}
if (card.split('\n').length < before.split('\n').length - 1) fail('poster-card.tsx menyusut tidak wajar');

// 3) tulis
if (!homeDone) fs.writeFileSync(HOME, NEW_HOME);
if (card !== before) fs.writeFileSync(CARD, card);
console.log('OK: home-mobile.tsx ' + (homeDone ? 'sudah terpasang' : 'ditulis (' + NEW_HOME.split('\n').length + ' baris)') + ', poster-card.tsx ' + (cardDone === R.length ? 'sudah terpasang' : 'disetel'));
